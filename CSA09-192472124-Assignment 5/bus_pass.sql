CREATE DATABASE IF NOT EXISTS transport_db;
USE transport_db;
CREATE TABLE IF NOT EXISTS bus_pass (
 pass_id VARCHAR(20) PRIMARY KEY,
 reg_no VARCHAR(20) NOT NULL,
 name VARCHAR(100) NOT NULL,
 route_no INT NOT NULL,
 amount DECIMAL(10,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS users (id VARCHAR(50) PRIMARY KEY, pwd VARCHAR(255) NOT NULL);
CREATE TABLE IF NOT EXISTS wallet (wallet_id BIGINT PRIMARY KEY, balance DECIMAL(12,2) NOT NULL);
